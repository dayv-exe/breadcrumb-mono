function generateProfessionVariants(): string[] {
  const people = ["🧑", "👨", "👩"];
  const out: string[] = [];

  for (const role of PROFESSION_ROLES) {
    for (const p of people) {
      out.push(`${p}‍${role}`); // ZWJ joiner
    }
  }
  return out;
}

